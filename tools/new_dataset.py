#!/usr/bin/env python3
"""Generate a dataset scaffold that already passes the five gates.

    python3 tools/new_dataset.py --kind qa      my_dataset \\
        --source-url https://… --source-version <pin> --source-size … \\
        --source-note "the trap this source has"
    python3 tools/new_dataset.py --kind command my_dataset --source-url …

The provenance is **required**, not optional: `tools/dataset_lint.py` refuses a dataset
whose `downloads()` is empty, because a dataset has to name where its bytes came from, and
writing `downloads()` is step 3 of the procedure for the same reason. Pinning it at
generation time means the decision is made before the loader is written, which is where
this repository has repeatedly found its worst surprises.

The scaffold is not a skeleton with TODOs. It is **a small working dataset** -- a toy table
generated in memory, a real scorer, a real check, a real control -- so that
`oracle = 1`, `noop = 0`, lint and the platform path are all *already true* when the author
starts. What the author replaces is the data and the metric; what they inherit is the
wiring, which is the part that is easy to get subtly wrong and impossible to notice.

That is the whole argument for generating rather than copying: sixteen datasets produced
this repository, and every one of them re-derived the same wiring by hand.

**Kinds.** `qa` uses the shared scaffold in `data/qa/` (its CLI, its check, its control and
its oracle harness): the author writes only the adapter. `command` is for a dataset whose
agent leaves an *artefact* that a program judges -- it generates `verify/check.py`, a
ten-line `control.py` over `data/command_control.py`, and nothing else.

**`--kind files` is deliberately not implemented yet.** That shape is a runtime tree plus
`lib/` + `cli/` + a `VERIFY.inputs` materialisation list, and it should be written once,
against the family that will share it (the tool-sandbox batch in `docs/survey/README.md`
§3.1), rather than guessed at now from one example. The refusal below says so out loud
instead of generating something that half works.

The generated module declares `KIND = "fixture"`, so a scaffold never appears in
`data.registry.published()` and never reaches the chooser. Flip it to `"dataset"` when the
real data and the official scorer are in.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from string import Template

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

NAME_RE = re.compile(r"^[a-z][a-z0-9_]{0,63}$")

KINDS = ("qa", "command")

#: How many toy rows the scaffold carries. Chosen at generation time to be at least this
#: many, then grown until `data/qa/base.is_eval` puts tasks on **both** sides of the split:
#: the split is hashed from the task id, which contains the dataset name, so the number of
#: rows a given name needs is not knowable without computing it. A scaffold that fails
#: `load()` because every task landed on one side would be a scaffold that does not work.
TOY_ROWS_MIN = 24


# --------------------------------------------------------------------------- QA ---

QA_TEMPLATE = Template('''"""$name: generated by `python3 tools/new_dataset.py --kind qa`.

**This scaffold already passes the five gates.** Replace the data and the metric; keep the
wiring. The procedure is `docs/dataset-onboarding.md`; the lessons are
`docs/dataset-onboarding-skill.md`.

Next steps, in the order that document gives them:

1. read the upstream scorer and transcribe it into `score()`;
2. point `_rows()` at the real table, fetched from `DOWNLOADS` below;
3. add `tests/quality/test_${name}_official_scorer.py` -- the verbatim copy plus a drift
   test -- and add `"$name"` to the parameter list in
   `tests/quality/test_qa_dataset_contract.py`;
4. delete `provision_status()` below so `_SPEC.provision_status()` answers instead;
5. flip `KIND` to `"dataset"`;
6. run the definition of done: `docs/dataset-onboarding.md` section 6.

The toy rows are generated in memory on purpose. They make `--oracle` reach 1 and `--noop`
reach 0 before a single byte of real data is on disk, which is the state you want to be in
before you start debugging someone else's loader.
"""
from __future__ import annotations

import re

from data.qa import base

KIND = "fixture"          # <- flip to "dataset" when the data and scorer are real

DATASET_ROOT = base.Path("/mnt/20t/xubuqiang/datasets/${name}")

#: The scaffold's table, generated in memory. Replace it with the real one.
ROWS: list[dict] = $rows

#: The provenance, declared before anything was written -- step 3 of the ten-step order.
DOWNLOADS: list[dict] = $downloads


def _rows() -> dict[str, list[dict]]:
    return {"test": ROWS}


def _question(row: dict) -> str:
    return str(row["question"])


def _gold(row: dict) -> dict:
    return {"answer": str(row["answer"])}


def _normalize(text: str) -> str:
    """Lower-case, strip punctuation, collapse whitespace.

    Deliberately shallow. A normalisation is part of the metric: if the official scorer
    lower-cases and strips articles, copy *that*; if it compares raw bytes, compare raw
    bytes. Do not helpfully normalise more than the benchmark does.
    """
    return " ".join(re.sub(r"[^a-z0-9 ]+", " ", (text or "").lower()).split())


def score(prediction: str, gold: dict) -> dict:
    """The grade. This is where the dataset's real metric goes.

    The contract is `docs/dataset-onboarding.md` section 3: return a dict with a numeric
    `reward`, and put the evidence in `official` and `why`. A metric that cannot be
    computed from `(prediction, gold)` is a refusal, not a nearby number.
    """
    want = str(gold.get("answer", ""))
    hit = _normalize(prediction) == _normalize(want)
    return {
        "reward": 1.0 if hit else 0.0,
        "correct": hit,
        "official": {"metric": "normalised exact match",
                     "label": want,
                     "normalized_prediction": _normalize(prediction)},
        "why": (f"{'matches' if hit else 'no match for'} "
                f"{_normalize(prediction)!r} vs {_normalize(want)!r}"),
    }


def _goal(question: str, gold: dict) -> str:
    return (
        f"{question}\\n\\n"
        "Answer with the value alone -- the whole answer is compared, so an explanation "
        "turns a correct answer into a wrong one.\\n\\n"
        "## How to answer\\n\\n"
        "`python3 qa/bin/qa submit <answer>` writes it; `python3 qa/bin/qa show` prints "
        "what you wrote.\\n"
    )


_SPEC = base.QASpec(
    name="$name",
    root=DATASET_ROOT,
    rows=_rows,
    question=_question,
    gold=_gold,
    goal=_goal,
    score=score,
    # Declared at generation time, because step 3 of the procedure is "write downloads()
    # first" -- and because `tools/dataset_lint.py` refuses a dataset that names no
    # provenance at all. The scaffold's own rows are in memory, so nothing here is fetched
    # until you wire the table to it.
    downloads=lambda: DOWNLOADS,
    split="test",
    source=$source,
)

_BUILT = _SPEC.build()

DEFAULT_ENV = _BUILT["DEFAULT_ENV"]
ENV = _BUILT["ENV"]
SPLIT = _BUILT["SPLIT"]
_RECORDS = _SPEC.ensure()


def __getattr__(name: str):
    return base.module_getattr(_SPEC, name)


def load() -> tuple[list[dict], dict[str, str]]:
    return _SPEC.load()


def downloads() -> list[dict]:
    return _SPEC._downloads()


def provision_status() -> dict:
    """The scaffold's rows are in memory, so the dataset runs without being provisioned.

    That is true **only while the table above is the toy one.** Delete this function as
    soon as `ROWS` comes from the declared source: `_SPEC.provision_status()` checks
    whether the declared artefacts are on disk, which is the answer the lint and
    `tools/datasets.py --check` want.
    """
    return {"root": str(DATASET_ROOT), "present": True, "split_dir": str(DATASET_ROOT),
            "tasks": len(_RECORDS)}


__all__ = ["KIND", "DATASET_ROOT", "ROWS", "load", "downloads", "score",
           "SPLIT", "ENV"]
''')


def _toy_rows(name: str) -> list[dict]:
    """A toy table sized so the hashed split has tasks on both sides for *this* name."""
    from data.qa.base import is_eval

    count = TOY_ROWS_MIN
    while True:
        rows = [{"question": f"What is {7 + i} + {5 + i}?",
                 "answer": str((7 + i) + (5 + i))} for i in range(count)]
        sides = {is_eval(f"{name}/test/{i}") for i in range(count)}
        if sides == {True, False}:
            return rows
        count += 1


# ---------------------------------------------------------------------- command ---

COMMAND_TEMPLATE = Template('''"""$name: generated by `python3 tools/new_dataset.py --kind command`.

**This scaffold already passes the five gates.** The `command` kind is for a dataset whose
agent leaves an *artefact* in the workdir -- a program, a CSV, a label -- and a check
program judges it. The procedure is `docs/dataset-onboarding.md`.

What is generated:

    data/$name.py                this adapter: SETUP, VERIFY, ENV, SPLIT, oracle_files()
    data/$name/verify/check.py   the check: reads the artefact, writes the reward
    data/$name/control.py        a shim over data/command_control.py

Next steps:

1. replace `TASKS` with the real task table (`load()` must keep returning `(tasks, scorable)`);
2. replace `verify/check.py` with the official scorer, transcribed, and add
   `tests/quality/test_${name}_official_scorer.py` with a drift test against upstream;
3. keep `oracle_files()` truthful -- gate 1 is only meaningful if it produces what a
   correct agent would have produced;
4. flip `KIND` to `"dataset"`;
5. run the definition of done: `docs/dataset-onboarding.md` section 6.

The toy task is "write the upper-case form of a word to `answer.txt`", which needs no
download, no runtime and no network, so the whole control loop is exercisable immediately.
"""
from __future__ import annotations

import json
from pathlib import Path

KIND = "fixture"          # <- flip to "dataset" when the data and scorer are real

DATASET_ROOT = Path("/mnt/20t/xubuqiang/datasets/$name")

#: Where the check writes its grade. The platform owns these names.
REWARD_FILE = "/verifier/reward.txt"
EVIDENCE_FILE = "/verifier/evidence.json"
REWARD_REL = "verifier/reward.txt"
EVIDENCE_REL = "verifier/evidence.json"

CHECK = Path(__file__).resolve().parent / "$name" / "verify" / "check.py"

#: The scaffold's task table. Replace with the real one.
TASKS: list[dict] = $tasks

#: Declared at generation time -- step 3 of the ten-step order, and the lint refuses a
#: dataset that names no provenance at all. Nothing here is fetched while the table above
#: is the toy one.
DOWNLOADS: list[dict] = $downloads

_GOLD = {t["task_id"]: t["gold"] for t in TASKS}


def _goal(task: dict) -> str:
    return (
        f"{task['question']}\\n\\n"
        "Write the answer to `answer.txt` in this directory (the file name is part of the "
        "contract), then stop. A program reads that file; nothing you print is graded.\\n"
    )


def load() -> tuple[list[dict], dict[str, str]]:
    tasks = [{"task_id": t["task_id"], "goal": _goal(t), "inputs": []} for t in TASKS]
    return tasks, dict(_GOLD)


def downloads() -> list[dict]:
    return DOWNLOADS


def provision_status() -> dict:
    """The scaffold's rows are in memory; see the note in the `qa` template."""
    return {"root": str(DATASET_ROOT), "present": True, "split_dir": str(DATASET_ROOT),
            "tasks": len(TASKS)}


ENV = {t["task_id"]: {"kind": "files"} for t in TASKS}

SETUP = {
    t["task_id"]: {"files": [
        {"path": "task.json", "content": json.dumps(
            {"task_id": t["task_id"], "question": t["question"]}, indent=1)},
    ]}
    for t in TASKS
}

VERIFY = {
    t["task_id"]: {
        "kind": "command",
        "argv": ["python3", "verify/check.py",
                 "--reward-file", REWARD_REL, "--evidence-file", EVIDENCE_REL],
        # Everything the check needs travels here: the verification namespace hides the
        # platform tree, so a check that imported this adapter would work by hand and fail
        # under `--platform`.
        "inputs": [
            {"path": "verify/check.py", "from": str(CHECK)},
            {"path": "gold.json", "content": json.dumps({"answer": _GOLD[t["task_id"]]})},
        ],
        "reward_file": REWARD_FILE,
        "evidence_file": EVIDENCE_FILE,
    }
    for t in TASKS
}

SPLIT = {"train": [t["task_id"] for t in TASKS[: max(1, len(TASKS) // 3)]],
         "eval": [t["task_id"] for t in TASKS[max(1, len(TASKS) // 3):]]}


def oracle_files(task: dict) -> dict[str, str]:
    """What a correct agent would leave in the workdir, as {relative path: content}.

    This is the dataset's reference solution as data, and `data/command_control.py` uses it
    for both arms: by hand it writes these files into the workdir, and through the platform
    it stages them at `.oracle/` for `data/command_oracle_harness/` to copy into place.
    """
    return {"answer.txt": _GOLD[task["task_id"]] + "\\n"}


__all__ = ["KIND", "DATASET_ROOT", "TASKS", "load", "downloads", "oracle_files",
           "SPLIT", "ENV", "SETUP", "VERIFY"]
''')

COMMAND_CHECK_TEMPLATE = Template('''#!/usr/bin/env python3
"""$name: the check. Generated by `tools/new_dataset.py --kind command`.

It runs with the task workdir as its working directory, reads the artefact the agent left,
compares it with the gold `VERIFY.inputs` re-materialised, and writes the grade. The
platform's rules for a check (`docs/dataset-onboarding.md` section 3):

* everything it imports travels in `VERIFY.inputs` -- it may **not** import the platform
  tree, because the verification namespace hides it;
* it writes `reward.txt` and `evidence.json`, and exits 0;
* a check that cannot measure writes **no** reward file, says `measured: false` and why,
  and exits 3 -- "unmeasured" is not "failed";
* an empty or missing artefact is a **measured zero**: the task ran and the agent left
  nothing, which is a real result.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--answer", default="answer.txt")
    parser.add_argument("--gold", default="gold.json")
    parser.add_argument("--reward-file", default="verifier/reward.txt")
    parser.add_argument("--evidence-file", default="verifier/evidence.json")
    args = parser.parse_args()

    work = Path.cwd()
    gold = json.loads((work / args.gold).read_text(encoding="utf-8"))["answer"]
    answer_path = work / args.answer
    prediction = answer_path.read_text(encoding="utf-8").strip() if answer_path.is_file() else ""

    hit = prediction.strip().lower() == str(gold).strip().lower()
    reward = 1.0 if hit else 0.0
    _write(work / args.reward_file, f"{reward:g}\\n")
    _write(work / args.evidence_file, json.dumps({
        "measured": True,
        "official": {"metric": "case-insensitive exact match on answer.txt",
                     "label": gold},
        "reward": reward,
        "prediction": prediction[:2000],
        "why": f"{'matches' if hit else 'no match for'} {prediction!r} vs {gold!r}",
    }, indent=1, sort_keys=True) + "\\n")
    print(f"reward {reward:g}: {'matches' if hit else 'no match for'} "
          f"{prediction!r} vs {gold!r}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
''')

COMMAND_CONTROL_TEMPLATE = Template('''#!/usr/bin/env python3
"""$name: the oracle and do-nothing controls.

    python3 data/$name/control.py --oracle
    python3 data/$name/control.py --noop
    python3 data/$name/control.py --oracle --platform
    python3 data/$name/control.py --noop   --platform

The algorithm lives in `data/command_control.py`; what is dataset-specific is
`oracle_files(task)` in `data/$name.py`, which is the reference solution as data.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from data import command_control  # noqa: E402


if __name__ == "__main__":
    raise SystemExit(command_control.control_main("$name", sys.argv[1:]))
''')


def _toy_tasks(name: str) -> list[dict]:
    words = ["alpha", "bravo", "charlie", "delta", "echo", "foxtrot", "golf", "hotel",
             "india", "juliet", "kilo", "lima", "mike", "november", "oscar", "papa",
             "quebec", "romeo", "sierra", "tango", "uniform", "victor", "whiskey",
             "xray", "yankee", "zulu"]
    return [{"task_id": f"{name}/eval/{i}", "question": f"Upper-case the word {word!r}.",
             "gold": word.upper()}
            for i, word in enumerate(words)]


# ------------------------------------------------------------------------- main ---

def generate(name: str, kind: str, source: dict, root: Path = ROOT) -> list[Path]:
    """Write the scaffold and return the paths, refusing to overwrite anything.

    `source` is the declared provenance: `url`, `version`, `size`, `note`, and optionally
    `sha256` and `dst`. It is required because `tools/dataset_lint.py` refuses a dataset
    whose `downloads()` is empty -- a dataset must name where its bytes came from -- and
    because step 3 of the procedure is to write `downloads()` before anything else.
    """
    if not NAME_RE.match(name):
        raise SystemExit(f"name {name!r} must match {NAME_RE.pattern}")
    if kind not in KINDS:
        raise SystemExit(_kind_refusal(kind))
    entry = _download_entry(name, source)

    module_path = root / "data" / f"{name}.py"
    targets = [module_path]
    if kind == "command":
        targets += [root / "data" / name / "verify" / "check.py",
                    root / "data" / name / "control.py"]
    existing = [p for p in targets if p.exists()]
    if existing:
        raise SystemExit("refusing to overwrite: "
                         + ", ".join(str(p.relative_to(root)) for p in existing))

    provenance = (f"tools/new_dataset.py --kind {kind} (scaffold); source: "
                  f"{source['url']} @ {source['version']}")
    common = {"name": name,
              "downloads": _py_literal([entry]),
              "source": _py_literal(provenance).replace('"', "'")}
    if kind == "qa":
        body = QA_TEMPLATE.substitute(rows=_py_literal(_toy_rows(name)), **common)
    else:
        body = COMMAND_TEMPLATE.substitute(tasks=_py_literal(_toy_tasks(name)), **common)
    module_path.write_text(body, encoding="utf-8")

    if kind == "command":
        check = root / "data" / name / "verify" / "check.py"
        control = root / "data" / name / "control.py"
        check.parent.mkdir(parents=True, exist_ok=True)
        check.write_text(COMMAND_CHECK_TEMPLATE.substitute(name=name), encoding="utf-8")
        control.write_text(COMMAND_CONTROL_TEMPLATE.substitute(name=name), encoding="utf-8")
        control.chmod(0o755)
        check.chmod(0o755)
    return targets


def _download_entry(name: str, source: dict) -> dict:
    """The one `downloads()` entry the scaffold starts with, validated here.

    Validating rather than emitting-and-hoping is deliberate: every trap this repository
    has paid for was a `downloads()` trap (skill doc §3, §7, §15.8), and a scaffold that
    emits an unpinned version teaches the wrong habit on the first line the author reads.
    """
    for key in ("url", "version", "size", "note"):
        if not str(source.get(key) or "").strip():
            raise SystemExit(f"--source-{key} is required: a dataset must name its "
                             f"provenance before anything is written (step 3 of the "
                             f"order in docs/dataset-onboarding.md)")
    if str(source["version"]).strip().lower() in (
            "", "main", "master", "head", "latest", "trunk", "dev", "nightly"):
        raise SystemExit(f"--source-version {source['version']!r} is a branch, not a pin; "
                         f"the schema refuses it and so does the lint")
    if len(str(source["note"])) < 20:
        raise SystemExit("--source-note must be at least 20 characters and must say what "
                         "the trap is; a note with no trap is a note the next person pays "
                         "for again")
    entry = {"kind": "http", "name": name, "version": str(source["version"]),
             "url": str(source["url"]), "size": str(source["size"]),
             "note": str(source["note"]), "dst": f"_src/{name}"}
    if source.get("sha256"):
        entry["sha256"] = str(source["sha256"])
    return entry


def _py_literal(value) -> str:
    """A `repr` that is stable and readable in a generated file."""
    return json.dumps(value, indent=4, ensure_ascii=False).replace("true", "True") \
        .replace("false", "False").replace("null", "None")


def _kind_refusal(kind: str) -> str:
    if kind == "files":
        return (
            "`--kind files` is deliberately not implemented yet.\n"
            "That shape is a runtime tree plus lib/, cli/ and a VERIFY.inputs "
            "materialisation list. It should be written once, against the family that will "
            "share it (the tool-sandbox batch in docs/survey/README.md section 3.1), rather "
            "than guessed at now from a single example. Until then, copy an existing "
            "`files` dataset -- data/jericho/ is the smallest -- and read "
            "docs/dataset-onboarding-skill.md sections 16-17 first.")
    return f"unknown kind {kind!r}; known kinds are {KINDS}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("name")
    parser.add_argument("--kind", required=True, choices=KINDS + ("files",))
    parser.add_argument("--source-url", required=True,
                        help="where the data comes from")
    parser.add_argument("--source-version", required=True,
                        help="the pin: a tag, a commit sha, a dataset revision")
    parser.add_argument("--source-size", required=True, help="how big it is")
    parser.add_argument("--source-note", required=True,
                        help="the trap this source has; at least 20 characters")
    parser.add_argument("--source-sha256", default=None, help="pin the bytes too")
    parser.add_argument("--root", default=str(ROOT))
    args = parser.parse_args(argv)

    source = {"url": args.source_url, "version": args.source_version,
              "size": args.source_size, "note": args.source_note,
              "sha256": args.source_sha256}
    written = generate(args.name, args.kind, source, Path(args.root))
    print(f"generated {args.name} ({args.kind}):")
    for path in written:
        print(f"  {path.relative_to(Path(args.root))}")
    print()
    print("the scaffold already passes the five gates; prove it:")
    if args.kind == "qa":
        print(f"  python3 tools/dataset_lint.py --dataset {args.name}")
        print(f"  python3 data/qa/control.py --dataset {args.name} --oracle")
        print(f"  python3 data/qa/control.py --dataset {args.name} --noop")
    else:
        print(f"  python3 tools/dataset_lint.py --dataset {args.name}")
        print(f"  python3 data/{args.name}/control.py --oracle")
        print(f"  python3 data/{args.name}/control.py --noop")
    print()
    print("then read docs/dataset-onboarding.md, which is the rest of the job.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
